"""Write the small auto-sector inverse table from the executed Python fixture; run after pins.py."""
import json
from pathlib import Path
kit=Path(__file__).resolve().parents[2]
p=json.loads((kit/'Tests/DiffractoOrientationTests/Fixtures/symmetry-pins.json').read_text())
names=['oneBar','twoOverM','mmm','fourOverM','fourOverMmm','threeBar','threeBarM','sixOverM','sixOverMmm','mThreeBar','mThreeBarM']
s='''// Generated by tools/symmetry/color-table.py from the pinned py4DSTEM automatic plan sectors.
// Inverse-transpose sector matrices are pinned to avoid platform-dependent inversion at runtime.
import Foundation
import simd
import DiffractoCore

extension CrystalOrientationSymmetry {
    internal var py4DSTEMBasis: [SIMD3<Double>] {
        switch laueClass {
'''
for name,record in zip(names,p['py4dstem']['records']):
 s+=f'        case .{name}: return [\n'
 s+=''.join('            SIMD3('+','.join(repr(float(v)) for v in row)+'),\n' for row in record['basis'])
 s+='        ]\n'
s+='''        }
    }

    internal func py4DSTEMColor(_ d: SIMD3<Double>) -> SIMD3<Float> {
        func clip(_ x: Double) -> Double { min(1,max(0,x)) }
        let rgb: SIMD3<Double>
        if laueClass == .twoOverM {
            // The 2/m "half" sector is [001],[010],[100]. NNLS of [A,-A] splits
            // the Cartesian components into positive/negative parts; no iterative solve is needed.
            let x = clip(d.x), nx = clip(-d.x), y = clip(abs(d.y)), z = clip(abs(d.z))
            rgb = [z+nx, z+y*0.3+x*0.7, z+y]
        } else {
            let a = py4DSTEMBasis
            var weights = a.map { clip(($0.x*d.x).addingProduct($0.y,d.y).addingProduct($0.z,d.z)) }
            let maximum = weights.max()!
            if maximum > 0 { weights = weights.map { $0/maximum } }
            rgb = [weights[0], weights[1]*0.7+weights[2]*0.3, weights[2]]
        }
        return SIMD3(Float(clip(rgb.x)),Float(clip(rgb.y)),Float(clip(rgb.z)))
    }
}
'''
(kit/'Sources/DiffractoOrientation/Py4DSTEMIPFKey.swift').write_text(s)
